package edu.mctc.gradebook;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.NoSuchElementException;
import java.util.Optional;

/**
 * Stores students and scores in a SQL database (H2).
 *
 * This is a DATABASE dependency. For Lab 10 integration tests, give each test
 * its own in-memory database so every test starts clean, e.g.
 *
 * <pre>
 * Connection conn = DriverManager.getConnection("jdbc:h2:mem:test" + System.nanoTime());
 * StudentRepository repo = new StudentRepository(conn);
 * </pre>
 */
public class StudentRepository {

    private final Connection conn;

    public StudentRepository(Connection conn) throws SQLException {
        this.conn = conn;
        createSchema();
    }

    private void createSchema() throws SQLException {
        try (Statement st = conn.createStatement()) {
            st.execute("""
                    CREATE TABLE IF NOT EXISTS students (
                        student_id VARCHAR(20) PRIMARY KEY,
                        name       VARCHAR(100) NOT NULL
                    )""");
            st.execute("""
                    CREATE TABLE IF NOT EXISTS scores (
                        id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        student_id VARCHAR(20) NOT NULL REFERENCES students(student_id),
                        category   VARCHAR(50) NOT NULL,
                        score      DOUBLE NOT NULL
                    )""");
        }
    }

    /** Add a student, or update the name if the id already exists. */
    public void addStudent(String studentId, String name) throws SQLException {
        try (PreparedStatement ps = conn.prepareStatement(
                "MERGE INTO students (student_id, name) KEY (student_id) VALUES (?, ?)")) {
            ps.setString(1, studentId);
            ps.setString(2, name);
            ps.executeUpdate();
        }
    }

    /** @throws NoSuchElementException if the student does not exist */
    public void addScore(String studentId, String category, double score) throws SQLException {
        if (getStudentName(studentId).isEmpty()) {
            throw new NoSuchElementException("unknown student: " + studentId);
        }
        try (PreparedStatement ps = conn.prepareStatement(
                "INSERT INTO scores (student_id, category, score) VALUES (?, ?, ?)")) {
            ps.setString(1, studentId);
            ps.setString(2, category);
            ps.setDouble(3, score);
            ps.executeUpdate();
        }
    }

    public Optional<String> getStudentName(String studentId) throws SQLException {
        try (PreparedStatement ps = conn.prepareStatement(
                "SELECT name FROM students WHERE student_id = ?")) {
            ps.setString(1, studentId);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() ? Optional.of(rs.getString(1)) : Optional.empty();
            }
        }
    }

    public List<String> listStudentIds() throws SQLException {
        List<String> ids = new ArrayList<>();
        try (Statement st = conn.createStatement();
             ResultSet rs = st.executeQuery("SELECT student_id FROM students ORDER BY student_id")) {
            while (rs.next()) {
                ids.add(rs.getString(1));
            }
        }
        return ids;
    }

    /** Return {category: [score, ...]} for one student, in insertion order. */
    public Map<String, List<Double>> getScores(String studentId) throws SQLException {
        Map<String, List<Double>> result = new LinkedHashMap<>();
        try (PreparedStatement ps = conn.prepareStatement(
                "SELECT category, score FROM scores WHERE student_id = ? ORDER BY id")) {
            ps.setString(1, studentId);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    result.computeIfAbsent(rs.getString(1), k -> new ArrayList<>()).add(rs.getDouble(2));
                }
            }
        }
        return result;
    }
}
